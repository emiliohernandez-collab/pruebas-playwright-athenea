import { expect, test } from '@playwright/test';
import { DashboardPage } from '../pages/DashboardPage';
import { LoginPage } from '../pages/LoginPage';
import { OrganizationPage } from '../pages/OrganizationPage';

test('M05-17-7 — Super Administrador — Liberar ticket', async ({ page }) => {
  test.setTimeout(40_000);
  test.skip(!process.env.ATHENEA_USER || !process.env.ATHENEA_PASSWORD, 'Faltan credenciales');
  const login = new LoginPage(page);
  const org = new OrganizationPage(page);
  const dashboard = new DashboardPage(page);
  await login.open();
  await login.signIn(process.env.ATHENEA_USER!, process.env.ATHENEA_PASSWORD!);
  if (/SelectOrganizationAtLogin/i.test(page.url())) {
    await org.select(process.env.ATHENEA_ORGANIZATION ?? 'QA Checkout Stripe');
    await org.continue();
  }
  await login.expectAuthenticated();
  await dashboard.expectLoaded();
  await page.goto('/Tickets/AdminGroups');
  await expect(page.locator('body')).toContainText(/Grupos de soporte/i);
  await page.getByRole('button', { name: /Agregar|Nuevo grupo|Crear grupo/i }).first().click();
  const groupName = `QA M05-17 grupo ${Date.now()}`;
  const groupDialog = page.getByRole('dialog');
  await groupDialog.getByRole('textbox').first().fill(groupName);
  await groupDialog.getByRole('button', { name: /Guardar|Crear/i }).click();
  await expect(page.locator('body')).toContainText(groupName);
  await page.goto('/Tickets/AdminCategories');
  await expect(page.locator('body')).toContainText(/Categor[ií]as/i);
  const categoryRow = page.getByRole('row').filter({ hasText: /QA M05-03 editado/ }).first();
  await expect(categoryRow).toBeVisible();
  await categoryRow.getByRole('button').nth(1).click();
  const categoryDialog = page.getByRole('dialog');
  await categoryDialog.getByLabel(/Grupo de Soporte Default/i).selectOption({ label: groupName });
  await categoryDialog.getByRole('button', { name: /Guardar/i }).click();
  const subject = `QA M05-17 liberar ${Date.now()}`;
  await page.goto('/Tickets/Create');
  await expect(page.locator('body')).toContainText(/Crear Ticket/i);
  await page.getByLabel(/Asunto/i).fill(subject);
  await page.locator('[contenteditable="true"]').first().fill('Ticket temporal para validar liberar ticket.');
  await page.getByRole('combobox', { name: /Categoria/i }).selectOption({ label: 'QA M05-03 editado 1791851732658' });
  await page.getByRole('button', { name: /Crear Ticket/i }).last().click();
  await expect(page).toHaveURL(/\/Tickets\/Details\//);
  await expect(page.locator('body')).toContainText(subject);
  const take = page.locator('#btnTakeTicket');
  await expect(take).toHaveCount(1);
  await take.evaluate((element: HTMLElement) => element.click());
  await page.waitForTimeout(700);
  const assignee = page.locator('#ticket-assignee');
  await expect(assignee).not.toHaveValue(/^(|null)$/i);
  const release = page.locator('#btnReleaseTicket');
  await expect(release).toHaveCount(1);
  await release.evaluate((element: HTMLElement) => element.click());
  const confirm = page.getByRole('button', { name: /Liberar|Confirmar|Sí/i }).last();
  if (await confirm.count() && await confirm.isVisible().catch(() => false)) await confirm.click();
  await page.waitForTimeout(700);
  await page.reload();
  await expect(page.getByRole('combobox').filter({ has: page.locator('option') }).last()).toHaveValue(/^(|null)$/i);
});
